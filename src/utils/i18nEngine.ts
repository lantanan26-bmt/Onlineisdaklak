export function translateViToEn(raw: string): string {
  if (!raw || !hasVietnameseChars(raw)) return raw;

  const leadMatch = raw.match(/^\s*/);
  const trailMatch = raw.match(/\s*$/);
  const lead = leadMatch ? leadMatch[0] : '';
  const trail = trailMatch ? trailMatch[0] : '';
  const normalized = raw.replace(/\s+/g, ' ').trim();
  if (!normalized) return raw;

  // 1. Exact dictionary lookup
  const exact = EXACT_MAP_LOWER.get(normalized);
  if (exact !== undefined) {
    return `${lead}${exact}${trail}`;
  }

  // Try without trailing colon if present
  if (normalized.endsWith(':')) {
    const noColon = normalized.slice(0, -1).trim();
    const m = EXACT_MAP_LOWER.get(noColon);
    if (m !== undefined) {
      return `${lead}${m.endsWith(':') ? m : `${m}:`}${trail}`;
    }
  }

  // 2. Pattern rules
  for (const [regex, replacer] of PATTERN_RULES) {
    const m = normalized.match(regex);
    if (m) {
      return `${lead}${replacer(...m)}${trail}`;
    }
  }

  // 3. Sub-phrase glossary fallback (only if text still has VN chars & is a UI string outside [data-preserve-content])
  let result = normalized;
  for (const [rx, rep] of SUB_GLOSSARY) {
    result = result.replace(rx, rep);
  }
  return `${lead}${result}${trail}`;
}
